#!/usr/bin/env python3
"""Colour audit: WCAG contrast of the four revision colours, and an inventory of every coloured span in paper/*.tex.

Writes tools/color_span_inventory.md (one row per coloured span: file, line, colour, first words).
"""
import pathlib, re

B = pathlib.Path(__file__).resolve().parents[1]
COL = {"RevA (RL5B, blue)": (0, 72, 190), "RevB (Caus, teal)": (0, 115, 115),
       "RevC (dypE, purple)": (105, 45, 160), "RevShared (2+ reviewers, orange)": (190, 85, 0)}


def lum(rgb):
    def ch(c):
        c /= 255
        return c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4
    r, g, b = (ch(x) for x in rgb)
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


print("Contrast against white (WCAG 2.x; >= 4.5 required for body text):")
for k, v in COL.items():
    ratio = 1.05 / (lum(v) + 0.05)
    print(f"  {k:34s} {ratio:5.2f}:1  {'PASS' if ratio >= 4.5 else 'FAIL'}")
print("Contrast against black (inverted/dark viewers):")
for k, v in COL.items():
    ratio = (lum(v) + 0.05) / 0.05
    print(f"  {k:34s} {ratio:5.2f}:1")

NAMES = {"A": "RL5B (blue)", "B": "Caus (teal)", "C": "dypE (purple)", "Shared": "shared (orange)"}
rows, counts = [], {k: 0 for k in NAMES}
pat = re.compile(r"\\rev(A|B|C|Shared)\{|\\begin\{revblock\}\{Rev(A|B|C|Shared)\}|\\revfloatcolor\{Rev(A|B|C|Shared)\}")
for f in sorted((B / "paper").glob("*.tex")):
    if f.name in ("REVISED_MARKED.tex", "REVISED_CLEAN.tex"):
        continue
    for i, line in enumerate(f.read_text().splitlines(), 1):
        if line.lstrip().startswith("\\DeclareRobustCommand") or line.lstrip().startswith("\\newenvironment") or line.lstrip().startswith("\\newcommand") or line.lstrip().startswith("\\definecolor"):
            continue
        for m in pat.finditer(line):
            k = m.group(1) or m.group(2) or m.group(3)
            counts[k] += 1
            kind = "span" if m.group(1) else ("block" if m.group(2) else "float")
            snippet = re.sub(r"\s+", " ", line[m.end():m.end() + 90]).replace("|", "/")
            rows.append(f"| {f.name} | {i} | {NAMES[k]} | {kind} | {snippet} |")
print("\nColoured spans by attribution:", {NAMES[k]: v for k, v in counts.items()})
out = B / "tools/color_span_inventory.md"
out.write_text("# Inventory of coloured spans (generated by tools/color_audit.py)\n\n"
               + "Counts: " + ", ".join(f"{NAMES[k]} {v}" for k, v in counts.items()) + "\n\n"
               + "| File | Line | Attribution | Kind | Starts with |\n|---|---|---|---|---|\n" + "\n".join(rows) + "\n")
print(f"wrote {out.relative_to(B)} ({len(rows)} spans)")
