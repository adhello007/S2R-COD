"""AN-03 step 5: reproduce the coverage and silhouette numbers the manuscript cites, instead of only citing them,
without touching the committed outputs (rebuild/A3/out, rebuild/B1/out are read, never written).

- k-NN coverage (Kynkaanniemi et al. 2019 recall of the real target set inside each pool's k-NN manifold):
  recomputed with independent numpy code from the E0 embedding caches, for every embedder and k in
  rebuild/A3/out/a3_coverage.csv, for the authors' pool, the LAKE-RED renders and the raw HKU-IS photographs.
- Silhouette at k = 75 (dinoL518): recomputed by calling the committed function step_cluster from
  rebuild/B1/b1_es_error_correlation.py (10 k-means seeds, silhouette on its fixed 2,000-image sample) on
  the committed target loader.
Writes RESULT_TABLES/AN03_reproduced_cited.csv/.md; exit code 1 if any value differs from the committed one
by more than 1e-4.
Usage: nice -n 19 taskset -c 40-47 .venv/bin/python analysis/an03_reproduce_cited.py
"""
import csv
import os
import sys

import numpy as np

import _repo as R

E0 = os.path.join(R.REPO, 'rebuild', 'E0', 'cache')
SETS = (("authors' pool", 'auth'), ('local renders', 'local'), ('raw HKU-IS (pre-LAKE-RED)', 'raw'))


def l2(x):
    x = x.astype(np.float64)
    return (x / np.linalg.norm(x, axis=1, keepdims=True)).astype(np.float32)


def sqd(a, b):
    return np.maximum((a * a).sum(1)[:, None] + (b * b).sum(1)[None, :] - 2.0 * a @ b.T, 0.0)


def recall(real, fake, k):
    d_ff = np.sqrt(sqd(fake, fake))
    np.fill_diagonal(d_ff, np.inf)
    r_f = np.partition(d_ff, min(k, len(fake) - 1) - 1, axis=1)[:, min(k, len(fake) - 1) - 1]
    d_rf = np.sqrt(sqd(real, fake))
    return float((d_rf <= r_f[None, :]).any(axis=1).mean())


def main():
    committed = list(csv.DictReader(open(os.path.join(R.REPO, 'rebuild', 'A3', 'out', 'a3_coverage.csv'))))
    rows, bad = [], 0
    for tag in sorted({r['embedder'] for r in committed}):
        tgt = l2(np.load(os.path.join(E0, '%s_tgt_cls.npy' % tag)))
        pools = {sk: l2(np.load(os.path.join(E0, '%s_%s_cls.npy' % (tag, sk)))) for _, sk in SETS}
        for k in sorted({int(r['k']) for r in committed}):
            for label, sk in SETS:
                c = [r for r in committed if r['embedder'] == tag and int(r['k']) == k and r['set'] == label][0]
                v = recall(tgt, pools[sk], k)
                ok = abs(v - float(c['recall'])) <= 1e-4
                bad += not ok
                rows.append(dict(quantity='k-NN recall of the real target', embedder=tag, k=k, set=label,
                                 reproduced='%.4f' % v, committed='%.4f' % float(c['recall']), match=ok))
    sys.path.insert(0, os.path.join(R.REPO, 'rebuild', 'B1'))
    import b1_es_error_correlation as B1
    X, _, _ = B1.load_target('dinoL518')
    s = B1.step_cluster(X, k_grid=(75,))[0]['silhouette_mean']
    c = [r for r in csv.DictReader(open(os.path.join(R.REPO, 'rebuild', 'B1', 'out', 'b1_k_sweep_dinoL518.csv'))) if r['k'] == '75'][0]
    ok = abs(s - float(c['silhouette_mean'])) <= 1e-4
    bad += not ok
    rows.append(dict(quantity='silhouette (mean of 10 k-means seeds)', embedder='dinoL518', k=75, set='target (leaked dropped)',
                     reproduced='%.4f' % s, committed='%.4f' % float(c['silhouette_mean']), match=ok))
    with open(os.path.join(R.TABLES, 'AN03_reproduced_cited.csv'), 'w', newline='') as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)
    gen = [float(r['reproduced']) for r in rows if r['k'] == 5 and r['set'] != 'raw HKU-IS (pre-LAKE-RED)' and 'recall' in r['quantity']]
    raw = [float(r['reproduced']) for r in rows if r['k'] == 5 and r['set'] == 'raw HKU-IS (pre-LAKE-RED)']
    md = ['# AN-03 step 5: the cited coverage and silhouette numbers, reproduced', '',
          '*Generated by `analysis/an03_reproduce_cited.py`; committed outputs are read, never written.*', '',
          '- At k = 5, the anchor k of the committed coverage analysis, across the three embedders: the generated pools '
          'have recall %.2f-%.2f and the raw source photographs %.2f-%.2f.' % (min(gen), max(gen), min(raw), max(raw)),
          '- Silhouette at k = 75 (dinoL518): %s (committed %s).' % (rows[-1]['reproduced'], rows[-1]['committed']),
          '- %d of %d values match the committed ones within 1e-4.' % (len(rows) - bad, len(rows)), '',
          '| Quantity | Embedder | k | Set | Reproduced | Committed | Match |', '|---|---|---|---|---|---|---|']
    md += ['| %(quantity)s | %(embedder)s | %(k)s | %(set)s | %(reproduced)s | %(committed)s | %(match)s |' % r for r in rows]
    open(os.path.join(R.TABLES, 'AN03_reproduced_cited.md'), 'w').write('\n'.join(md) + '\n')
    print('\n'.join(md[:8]))
    sys.exit(1 if bad else 0)


if __name__ == '__main__':
    main()
