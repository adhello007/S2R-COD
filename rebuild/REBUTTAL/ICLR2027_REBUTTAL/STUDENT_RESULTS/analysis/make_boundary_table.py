"""Generate revision/table_boundary_8seed.tex (replaces the three-seed tab:boundary in the revised manuscript).

Rows: SINet and SINet-v2, COD10K-test, binarisation 0.5, Boundary-IoU; the five contrasts of AN-01. Columns: the
eight-seed Delta, bar (2 x the SE campaign's pooled sigma-hat for this metric, df = 28), x bar, sign agreement and
verdict (>= 7/8 rule), plus the submitted three-seed x bar for comparison. Every value comes from
RESULT_TABLES/AN01_boundary_8seed.csv and rebuild/DIAG/out/diag_subgroups.json; nothing is typed by hand.
"""
import csv
import json
import os

import _repo as R

CONTRASTS = ('C10-B', 'CINV-B', 'CSHUF-B', 'C10-CSHUF', 'C10-CINV')
NAME = {'SINet': 'SINet', 'SINetv2': 'SINet-v2'}


def main():
    rows = [r for r in csv.DictReader(open(os.path.join(R.TABLES, 'AN01_boundary_8seed.csv')))
            if r['endpoint'] == 'COD10K' and r['thresh'] == '0.5' and r['metric'] == 'boundary_iou']
    three = json.load(open(os.path.join(R.REPO, 'rebuild', 'DIAG', 'out', 'diag_subgroups.json')))['whole_set']
    body = []
    for i, arch in enumerate(('SINet', 'SINetv2')):
        if i:
            body.append(r'\midrule')
        for k in CONTRASTS:
            r = [x for x in rows if x['arch'] == arch and x['contrast'] == k][0]
            t3 = three['%s|boundary_iou' % arch]['gaps'].get(k)
            hi, lo = k.split('-')
            body.append(r'%s & $\mathrm{%s}-\mathrm{%s}$ & $%+.4f$ & $%.4f$ & $%.2f$ & %s & %s & $%s$ \\' % (
                NAME[arch] if k == CONTRASTS[0] else '', hi, lo, float(r['delta']), float(r['bar']), float(r['xbar']),
                r['sign'], r['verdict'].lower().replace('within noise', r'\textsc{within noise}'),
                '%.2f' % t3['ratio'] if t3 else '\\text{--}'))
    tex = r"""%% Generated by analysis/make_boundary_table.py from RESULT_TABLES/AN01_boundary_8seed.csv -- do not edit by hand.
\begin{table}[t]
\caption{Boundary-IoU on COD10K-test at eight seeds per arm (binarisation threshold $0.5$; post hoc, decides
nothing). The bar is twice the eight-seed campaign's pooled seed-to-seed spread for this metric; an effect also
needs at least seven of eight seed-paired differences to agree in sign. The last column is the three-seed ratio in
the submitted version. Both SINet contrasts against random that cleared their bars at three seeds are within noise
at eight.}
\label{tab:boundary}
\begin{center}
\scriptsize
\setlength{\tabcolsep}{3.5pt}
\begin{tabular}{@{}llcccccc@{}}
\toprule
Arch. & Contrast & $\Delta$ & bar & $\times$\,bar & sign & verdict (8 seeds) & $\times$\,bar (3 seeds) \\
\midrule
""" + '\n'.join(body) + r"""
\bottomrule
\end{tabular}
\end{center}
\end{table}
"""
    open(os.path.join(R.STUDENT, 'revision', 'table_boundary_8seed.tex'), 'w').write(tex)
    print('\n'.join(body))


if __name__ == '__main__':
    main()
