"""Fill the manuscript's EQ macros (\\eqverdict, \\eqshort) from RESULT_TABLES/EXP01_EQ_summary.json.

The wording follows the pre-registered decision statements (prereg/EQ.md, EQ.5) and Amendment 1's
INCOMPLETE rule. The counts are the completed runs per arm, not the design n (EXECUTION_STATUS.md, deviation
25). Nothing is typed by hand. Writes revision/eq_result.tex.
Usage: python analysis/make_eq_sentences.py
"""
import json
import os

import _repo as R


def main():
    s = json.load(open(os.path.join(R.TABLES, 'EXP01_EQ_summary.json')))
    n = s['n_by_arm']
    ep = s['endpoints']['COD10K']
    h1, h1b = ep['contrasts']['C10-B'], ep['contrasts']['C10-CSHUF']
    w, wb = h1['welch'], h1b['welch']
    rule = ep['rule']['gaps']['C10-B']
    nc = s['endpoints']['NC4K']['contrasts']
    f = lambda x: '%+.4f' % x
    eq1 = w['p_tost'] < 0.05 and not (w['ci95'][0] > 0 or w['ci95'][1] < 0)
    if not eq1:
        raise SystemExit('H1 is not decision (i); write the sentence for the decision that applies')
    inc = (r', left incomplete by hardware interruptions at %d (random) and %d (targeted) of 27 planned seeds and '
           r'analysed in full as pre-registered,' % (n['B'], n['C10'])) if s['incomplete'] else ''
    nc_eq = all(nc[c]['welch']['p_tost'] < 0.05 for c in ('C10-B', 'C10-CSHUF'))
    verdict = (r'A separately pre-registered confirmatory campaign with fresh seeds' + inc +
               r' establishes equivalence within $\pm0.005$ on the primary cell ($\Delta = %s$, 90\%% CI $[%s, %s]$, '
               r'TOST $p = %.3f$; $2\hat\sigma$ rule: within noise). Against the shuffled arm it does not on COD10K-test '
               r'(TOST $p = %.3f$)%s.'
               % (f(w['delta']), f(w['ci90'][0]), f(w['ci90'][1]), w['p_tost'], wb['p_tost'],
                  '; on NC4K both contrasts are equivalent' if nc_eq else ''))
    short = (r'A pre-registered confirmatory campaign%s establishes equivalence within $\pm0.005$ on the primary '
             r'comparison (90\%% interval $%s$ to $%s$).'
             % (r', incomplete at %d--%d of 27 seeds per arm,' % (min(n.values()), max(n.values()))
                if s['incomplete'] else '', f(w['ci90'][0]), f(w['ci90'][1])))
    tex = ('%% Generated by analysis/make_eq_sentences.py from RESULT_TABLES/EXP01_EQ_summary.json -- do not edit by hand.\n'
           '\\renewcommand{\\eqverdict}{%s}\n\\renewcommand{\\eqshort}{%s}\n' % (verdict, short))
    open(os.path.join(R.STUDENT, 'revision', 'eq_result.tex'), 'w').write(tex)
    print(tex)


if __name__ == '__main__':
    main()
