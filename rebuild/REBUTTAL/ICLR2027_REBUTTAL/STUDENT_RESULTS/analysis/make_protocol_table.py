"""DOC-02: generate revision/table_protocol.tex and revision/gap_paragraph.tex from EXP-03 / AN-02 outputs.

Every number comes from RESULT_TABLES/EXP03_protocol_matched.csv (our scorer, or verified published values) and
RESULT_TABLES/EXP03_gap_decomposition.json; nothing is typed by hand. A missing value prints as an en dash.
"""
import csv
import json
import os

import _repo as R

ROWS = [  # (label in table, method key in EXP03_protocol_matched.csv, labels, target images, backbone, generator, how)
    ('Ours, targeted (C10)', 'Ours: targeted allocation (C10), SINet', 'synthetic', 'unlabelled', 'SINet (R50)', 'LAKE-RED', '8 seeds'),
    ('Ours, targeted (C10)', 'Ours: targeted allocation (C10), SINetv2', 'synthetic', 'unlabelled', 'SINet-V2 (R2-50)', 'LAKE-RED', '8 seeds'),
    ('S2R-COD (published)', 'S2R-COD SINet "Ours" (synthetic-to-real)', 'synthetic', 'unlabelled', 'SINet (R50)', 'HKU-IS synth.', 'paper'),
    ('S2R-COD (published)', 'S2R-COD SINet-v2 "Ours" (synthetic-to-real)', 'synthetic', 'unlabelled', 'SINet-V2 (R2-50)', 'HKU-IS synth.', 'paper'),
    ('RISE (released maps)', 'RISE, unsupervised (released maps, DINOv2-ViT-L14)', 'none', 'pseudo masks', 'SINet-V2 (R2-50)', 'none', 're-scored'),
    ('Supervised, our trainer', 'Real masks of the same 4040 images, single round, SINet', 'real masks', 'labelled', 'SINet (R50)', 'none', '3 seeds'),
    ('Supervised, our trainer', 'Real masks of the same 4040 images, single round, SINetv2', 'real masks', 'labelled', 'SINet-V2 (R2-50)', 'none', '3 seeds'),
    ('SINet-V2 (released maps)', 'SINet-V2, supervised (released maps)', 'real masks', 'labelled', 'SINet-V2 (R2-50)', 'none', 're-scored'),
]


def main():
    tab = {r['method']: r for r in csv.DictReader(open(os.path.join(R.TABLES, 'EXP03_protocol_matched.csv')))}
    v = lambda r, k: ('%.3f' % float(r[k])) if r.get(k) else '--'
    body = []
    for lab, key, labels, tgt, bb, gen, how in ROWS:
        r = tab[key]
        body.append(r'%s & %s & %s & %s & %s & %s & %s & %s & %s & %s & %s & %s \\' % (
            lab, labels, tgt, bb, gen, how, v(r, 'COD10K_Sm'), v(r, 'COD10K_meanEm'), v(r, 'COD10K_wFm'),
            v(r, 'NC4K_Sm'), v(r, 'NC4K_meanEm'), v(r, 'NC4K_wFm')))
    tex = r"""%% Generated by analysis/make_protocol_table.py from RESULT_TABLES/EXP03_protocol_matched.csv -- do not edit by hand.
\begin{table}[t]
\caption{Protocols and accuracy under one scorer and one set of test splits. ``Target images'' is how the 4,040
COD10K and CAMO training images enter training. Our rows are means over seeds; ``re-scored'' rows are released
prediction maps scored with our code, which reproduces every published value within $0.002$; S2R-COD rows are as
published (COD10K only). $E_\phi$ is the mean E-measure. The supervised rows are an upper reference, not a competitor.
R50: ResNet-50; R2-50: Res2Net-50; both ImageNet-pretrained.}
\label{tab:protocol}
\begin{center}
\tiny
\setlength{\tabcolsep}{2.2pt}
\begin{tabular}{@{}llllllcccccc@{}}
\toprule
& & & & & & \multicolumn{3}{c}{COD10K-test} & \multicolumn{3}{c}{NC4K} \\
\cmidrule(lr){7-9}\cmidrule(l){10-12}
Method & Labels & Target images & Detector & Generator & $n$ & $S_\alpha$ & $E_\phi$ & $F_\beta^w$ & $S_\alpha$ & $E_\phi$ & $F_\beta^w$ \\
\midrule
""" + '\n'.join(body) + r"""
\bottomrule
\end{tabular}
\end{center}
\end{table}
"""
    open(os.path.join(R.STUDENT, 'revision', 'table_protocol.tex'), 'w').write(tex)
    gap = json.load(open(os.path.join(R.TABLES, 'EXP03_gap_decomposition.json')))
    g = {(x['component'], x['arch'], x['endpoint']): x['delta'] for x in gap}
    para = (r"%% Generated by analysis/make_protocol_table.py from RESULT_TABLES/EXP03_gap_decomposition.json -- do not edit by hand." "\n"
            r"\paragraph{Where the absolute gap comes from.} Table~\ref{tab:protocol} places our pipeline beside the method it "
            r"builds on, RISE, and supervised SINet-V2 under one scorer. Most of the gap to supervised SINet-V2 is the "
            r"absence of real labels: training our own pipeline on the real masks of the same 4,040 images, in a single "
            r"round and with our recipe, raises $S_\alpha$ on COD10K-test by $%+.3f$ for SINet-V2 and $%+.3f$ for SINet over "
            r"the targeted synthetic-to-real arm, while the official SINet-V2 recipe adds only $%+.3f$ on top of that. RISE "
            r"exceeds our SINet-V2 arm by $%+.3f$ on COD10K-test and $%+.3f$ on NC4K; since its detector and training images are "
            r"ours, that gap reflects pseudo masks on the real target images against synthetic renders plus self-training, "
            r"though without training our recipe on RISE's masks we cannot separate the quality of its supervision from its "
            r"training recipe. These differences overlap and do not add up to the total gap. None of them changes the "
            r"comparison this paper is about, which holds the pipeline fixed and varies only the allocation." % (
                g[('label supervision, our recipe', 'SINetv2', 'COD10K')], g[('label supervision, our recipe', 'SINet', 'COD10K')],
                g[('recipe and reproduction', 'SINetv2', 'COD10K')],
                g[('unsupervised method and target supervision', 'SINetv2', 'COD10K')],
                g[('unsupervised method and target supervision', 'SINetv2', 'NC4K')]))
    open(os.path.join(R.STUDENT, 'revision', 'gap_paragraph.tex'), 'w').write(para + '\n')
    print(para)


if __name__ == '__main__':
    main()
