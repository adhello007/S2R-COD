"""TH-01 step 7: one-page reviewer-facing explanation of "not detected" versus "equivalent", with the actual
numbers. Every number is read from TH-01's generated outputs (TH01_contrasts.csv, TH01_rule_sensitivity.csv,
TH01_summary.json); nothing is typed by hand. Writes RESULT_TABLES/TH01_explainer.md.
"""
import csv
import json
import os

import _repo as R


def main():
    rows = list(csv.DictReader(open(os.path.join(R.TABLES, 'TH01_contrasts.csv'))))
    sens = [r for r in csv.DictReader(open(os.path.join(R.TABLES, 'TH01_rule_sensitivity.csv')))
            if r['arch'] == 'SINet' and r['endpoint'] == 'COD10K']
    p = [r for r in rows if r['arch'] == 'SINet' and r['endpoint'] == 'COD10K' and r['contrast'] == 'C10-B'][0]
    nc = [r for r in rows if r['arch'] == 'SINet' and r['endpoint'] == 'NC4K' and r['contrast'] == 'C10-B'][0]
    at = {float(r['true_delta']): r for r in sens}
    f = lambda x: '%+.4f' % float(x)
    n_eq = sum(r['label'] in ('equivalent', 'detected and equivalent') for r in rows)
    n_det = sum(r['label'] in ('detected', 'detected and equivalent') for r in rows)
    n_eq_h = sum(r['label_holm'] in ('equivalent', 'detected and equivalent') for r in rows)
    mde_rule = float(at[0.005]['mde80_sim_rule_7of8'])
    txt = f"""# Not detected versus equivalent: what the eight-seed data show

*Generated by `analysis/th01_explainer.py` from TH-01's outputs. Post hoc: the ±0.005 margin was chosen after
the eight-seed campaign, and nothing here changes a pre-registered verdict.*

Two different questions can be asked of a difference between two training recipes. **Did we detect a
difference?** Yes, if the 95% confidence interval for the difference excludes zero. **Did we show the recipes are
equivalent?** Yes, if the whole 90% interval sits inside a margin small enough not to matter; a two one-sided test
(TOST) at that margin then rejects. A result can satisfy neither: the interval contains zero, so nothing was
detected, but it is too wide to rule out a difference that would matter. That is a failure to detect, not evidence
of no effect.

**The primary comparison is in that middle category.** On SINet and COD10K-test, eight seeds per arm, targeted
allocation minus random allocation is Δ = {f(p['delta'])} S_α. Its 95% interval is [{f(p['ci95_lo'])}, {f(p['ci95_hi'])}]:
it contains zero, so no advantage is detected. Its 90% interval is [{f(p['ci90_lo'])}, {f(p['ci90_hi'])}], whose upper end
lies above +0.005, so equivalence at ±0.005 is not established (TOST p = {float(p['p_tost']):.3f}). What the data do
exclude is an advantage as large as the effect of the published method we build on (+0.0142): it lies well above the
interval. What they do not exclude is an advantage between about +0.005 and {f(p['ci95_hi'])}.

**Across all sixteen eight-seed contrasts** (two architectures, two test sets, four contrasts), {n_eq} reach
equivalence at ±0.005 and {n_det} has a 95% interval that excludes zero, each before correcting for multiple
comparisons. After a Holm correction across the sixteen, {('none reaches' if n_eq_h == 0 else str(n_eq_h) + ' reach')} equivalence and none is detected. The
targeting-versus-random contrast reaches equivalence on NC4K (Δ = {f(nc['delta'])}, TOST p = {float(nc['p_tost']):.3f})
but not on the primary test set.

**How sensitive was the decision rule?** The pre-registered rule declares an effect only when the gap exceeds
twice the pooled seed-to-seed spread and at least seven of eight seed-paired differences agree in sign. Simulating
that rule exactly, with each arm's observed spread, it would catch a true advantage of +0.005 only
{float(at[0.005]['p_sim_rule_7of8']):.0%} of the time, and of +0.0083 {float(at[0.0083]['p_sim_rule_7of8']):.0%} of the
time; it catches the reference-size effect (+0.0142) {float(at[0.0142]['p_sim_rule_7of8']):.1%} of the time. The effect it
detects with 80% probability is about {mde_rule:.4f}. The rule was therefore built to detect reference-size effects,
and it cannot rule out effects near the margin.

**A correction to our initial response.** We stated that a true effect of 0.005 would clear the rule "with
probability only about 0.14", and that the 80% detectable effect is "about 0.008". Those figures used a normal
approximation with a fixed pooled spread. The exact simulation gives {float(at[0.005]['p_sim_rule_7of8']):.2f} and
{mde_rule:.4f}: the rule is somewhat more sensitive at the margin than we said, and its 80% detectable effect is
slightly larger. The conclusion is unchanged.
"""
    open(os.path.join(R.TABLES, 'TH01_explainer.md'), 'w').write(txt)
    print('written; %d words' % len(txt.split()))


if __name__ == '__main__':
    main()
