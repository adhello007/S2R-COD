"""App. C 'binarisation sweep' paragraph: the committed three-seed sweep (the submission's own figures,
reproduced by the AN-01 gate), followed by the eight-seed sweep generated from
RESULT_TABLES/AN01_boundary_8seed.csv. The submitted paragraph presented the three-seed sweep as the current
result; the eight-seed sweep supersedes it. Writes revision/boundary_sweep.tex.
Usage: python analysis/make_boundary_sweep.py
"""
import csv
import os

import _repo as R


def main():
    rows = [r for r in csv.DictReader(open(os.path.join(R.TABLES, 'AN01_boundary_8seed.csv')))
            if r['arch'] == 'SINet' and r['endpoint'] == 'COD10K' and r['metric'] == 'boundary_iou']
    x = {(r['contrast'], r['thresh']): float(r['xbar']) for r in rows}
    verdicts = {r['verdict'] for r in rows}
    ts = ('0.4', '0.5', '0.6')
    f = lambda c: '/'.join('%.2f' % x[(c, t)] for t in ts)
    direction_max = max(x[(c, t)] for c in ('C10-CSHUF', 'C10-CINV') for t in ts)
    assert verdicts == {'WITHIN NOISE'}, verdicts
    tex = (r"%% Generated by analysis/make_boundary_sweep.py from RESULT_TABLES/AN01_boundary_8seed.csv -- do not edit by hand." "\n"
           r"\paragraph{Boundary metrics: the binarisation sweep in full.} Boundary metrics binarise a prediction where "
           r"$S_\alpha$ does not, so a threshold could create or hide an effect. At the committed three seeds, swept over "
           r"thresholds $0.4 / 0.5 / 0.6$ on SINet Boundary-IoU~\citep{cheng2021boundary}, $\Delta(\mathrm{C10}-\mathrm{B})$ "
           r"sat at $1.39 / 1.37 / 1.23\times$ its bar and $\Delta(\mathrm{CINV}-\mathrm{B})$ at $1.25 / 1.34 / 1.26\times$, "
           r"while the two direction contrasts never exceeded $0.52\times$ and $0.14\times$. At eight seeds the same sweep "
           r"gives $%s\times$ and $%s\times$, and the direction contrasts stay at or below $%.2f\times$: every contrast is "
           r"within noise at every threshold (Table~\ref{tab:boundary} shows threshold $0.5$). The threshold changes neither "
           r"reading; the seed count does." "\n"
           % (f('C10-B').replace('/', ' / '), f('CINV-B').replace('/', ' / '), direction_max))
    open(os.path.join(R.STUDENT, 'revision', 'boundary_sweep.tex'), 'w').write(tex)
    print(tex)


if __name__ == '__main__':
    main()
