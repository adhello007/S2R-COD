"""Fill the manuscript's dose-response placeholders from the pre-registered decision sentence (prereg/CDR.md, CDR.6),
with numbers read from RESULT_TABLES/EXP02_SINet_summary.json. Writes revision/cdr_result.tex (\\renewcommand's)."""
import json
import os

import _repo as R

s = json.load(open(os.path.join(R.TABLES, 'EXP02_SINet_summary.json')))
P = s['analyses']['PRIMARY BIoU@0.5 COD10K']
assert P['conclusion'] == 'not supported', P['conclusion']
lv = P['levels']
big = max(lv.values(), key=lambda l: abs(l['delta']))
sec = [a for k, a in s['analyses'].items() if k.startswith('secondary') and 'COD10K' in k]
any_sec = any(a['conclusion'] != 'not supported' for a in sec)
verdict = (r"It did not support a downstream effect of concentration. On SINet the twice-as-concentrated level differs from "
           r"the dispersed references by $%+.4f$ Boundary-IoU and the committed shape by $%+.4f$, against a bar of $%.4f$ "
           r"($%.2f\times$ and $%.2f\times$)%s. We therefore restrict the concentration claim to the training-set "
           r"distribution: concentration explains why targeted training sets look different, not a change in accuracy." % (
               lv['LH']['delta'], lv['L1']['delta'], P['bar'], lv['LH']['xbar'], lv['L1']['xbar'],
               '' if any_sec else r', and no secondary measure on COD10K-test, $S_\alpha$ included, clears its bar'))
short = (r"A pre-registered dose-response experiment found no downstream effect of concentration on accuracy, so the "
         r"concentration claim is restricted to the training sets.")
open(os.path.join(R.STUDENT, 'revision', 'cdr_result.tex'), 'w').write(
    "%% Generated by analysis/make_cdr_sentences.py from RESULT_TABLES/EXP02_SINet_summary.json -- do not edit by hand.\n"
    "\\renewcommand{\\cdrverdict}{%s}\n\\renewcommand{\\cdrshort}{%s}\n" % (verdict, short))
print(verdict, '\n', short, '\n largest level:', big['delta'])
