"""EXP-02 deliverables named in the instructions (§5, EXP-02), generated from committed records:
- RESULT_TABLES/EXP02_allocations.csv: one row per CDR allocation, with rho, Jaccard to C10, the largest Jaccard
  to any other CDR set at the same level and to any CDR set at all, nominal and induced N_eff, fill distances,
  and the draw acceptance rate of its level. Sources: rebuild/ABC/out/cdr/cdr_allocations.csv (written at the
  draw, before any run), the stem lists rebuild/ABC/out/cdr/cdr_stems_*.txt, and EXPERIMENT_LOGS/EXP02_cdr_draw.log.
- RESULT_TABLES/EXP02_results.csv and .md: the per-level decision table for every measure, from
  RESULT_TABLES/EXP02_SINet_summary.json (written by the pre-registered analysis). The .md points to
  RESULT_TABLES/EXP02_SINet_results.md for the full report.
Usage: python analysis/make_exp02_tables.py
"""
import csv
import json
import os
import re

import _repo as R

CDR = os.path.join(R.REPO, 'rebuild', 'ABC', 'out', 'cdr')


def stems(arm):
    return set(open(os.path.join(CDR, 'cdr_stems_%s.txt' % arm)).read().split())


def main():
    al = list(csv.DictReader(open(os.path.join(CDR, 'cdr_allocations.csv'))))
    S = {a['arm']: stems(a['arm']) for a in al}
    J = lambda a, b: len(S[a] & S[b]) / len(S[a] | S[b])
    rate = {}
    for line in open(os.path.join(R.LOGS, 'EXP02_cdr_draw.log')):
        m = re.match(r'(L1|LH) tau [\d.]+: .*relaxation step (\d).*acceptance rate ([\d.]+)', line)
        if m:
            rate[m.group(1)] = (m.group(3), m.group(2))
    rows = []
    for a in al:
        same = [J(a['arm'], b['arm']) for b in al if b['arm'] != a['arm'] and b['level'] == a['level']]
        anyl = [J(a['arm'], b['arm']) for b in al if b['arm'] != a['arm']]
        rows.append(dict(arm=a['arm'], level=a['level'], mode=a['mode'], tau=a['tau'], draw_index=a['draw_index'],
                         rho=a['rho'], jaccard_c10=a['jaccard_c10'],
                         max_jaccard_same_level='%.4f' % max(same) if same else '',
                         max_jaccard_any_cdr='%.4f' % max(anyl),
                         n_eff_nominal=a['n_eff_nominal'], n_eff_induced=a['n_eff_induced'], max_quota=a['max_quota'],
                         clusters_funded=a['clusters_funded'], fill_dist_mean=a['fill_dist_mean'],
                         fill_dist_p90=a['fill_dist_p90'], fill_dist_max=a['fill_dist_max'],
                         level_acceptance_rate=rate.get(a['level'], ('', ''))[0],
                         relaxation_step=rate.get(a['level'], ('', ''))[1], stems_sha256=a['stems_sha256']))
    with open(os.path.join(R.TABLES, 'EXP02_allocations.csv'), 'w', newline='') as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)
    s = json.load(open(os.path.join(R.TABLES, 'EXP02_SINet_summary.json')))['analyses']
    res = []
    for name, v in s.items():
        for lev in ('L1', 'LH'):
            L = v['levels'][lev]
            res.append(dict(measure=name, level=lev, D=round(v['D'], 6), sigma_hat=round(v['sigma_hat'], 6), df=v['df'],
                            bar=round(v['bar'], 6), delta=round(L['delta'], 6), xbar=round(L['xbar'], 4),
                            perms_agree=L['perms_agree'], between_perm_sd=round(L['between_perm_sd'], 6),
                            a=L['a'], b=L['b'], c=L['c'], conclusion=v['conclusion'],
                            welch_units_delta=round(v['welch_units_reported']['delta'], 6),
                            welch_units_ci95_lo=round(v['welch_units_reported']['ci95'][0], 6),
                            welch_units_ci95_hi=round(v['welch_units_reported']['ci95'][1], 6)))
    with open(os.path.join(R.TABLES, 'EXP02_results.csv'), 'w', newline='') as fh:
        w = csv.DictWriter(fh, fieldnames=list(res[0]))
        w.writeheader()
        w.writerows(res)
    prim = [r for r in res if r['measure'].startswith('PRIMARY')]
    md = ['# EXP-02 (CDR) results, SINet', '',
          '*Generated by `analysis/make_exp02_tables.py` from `RESULT_TABLES/EXP02_SINet_summary.json`, the output of the '
          'pre-registered analysis. The full report, with the secondary measures and the descriptive analyses, is '
          '`RESULT_TABLES/EXP02_SINet_results.md`; every row is in `RESULT_TABLES/EXP02_results.csv`. SINet-v2 was not run.*', '',
          '**Primary (Boundary-IoU at 0.5, SINet COD10K-test): %s.** No secondary measure is supported: %d of %d measures "not supported".'
          % (prim[0]['conclusion'], sum(1 for n, v in s.items() if v['conclusion'] == 'not supported'), len(s)), '',
          '| Level | D | bar (2 sigma-hat, df %s) | Delta | x bar | permutations agreeing | between-permutation SD | (a) | (b) | (c) |' % prim[0]['df'],
          '|---|---|---|---|---|---|---|---|---|---|']
    md += ['| %(level)s | %(D).4f | %(bar).4f | %(delta)+.4f | %(xbar).2f | %(perms_agree)s | %(between_perm_sd).4f | %(a)s | %(b)s | %(c)s |' % r for r in prim]
    md += ['', 'Allocations (draw record, acceptance rates, Jaccards, N_eff, fill distances): `RESULT_TABLES/EXP02_allocations.csv`.']
    open(os.path.join(R.TABLES, 'EXP02_results.md'), 'w').write('\n'.join(md) + '\n')
    print('\n'.join(md))
    print('max Jaccard between any two CDR sets: %.4f' % max(float(r['max_jaccard_any_cdr']) for r in rows))


if __name__ == '__main__':
    main()
